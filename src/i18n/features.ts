function trWhat(w: string) {
  if (w === 'Golden Monster') return 'Monstruo Dorado';
  if (w === 'First to catch this legendary') return 'Primero en atrapar este legendario';
  return w.replace(/^Dex milestone (\d+)$/, 'Hito del Dex $1');
}
